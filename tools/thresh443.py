print('-' * 78)

# Petersen: uniformity demo at t = 2, 3, 4
nE = petersen(); n, E, adj, eidx = build(nE)
cycles = all_cycles(adj, n)
CP = [c for c in cycles if len(c) == 8][0]
for t in (2, 3, 4):
    analyze('Petersen', nE, CP, t, '8-cycle')

# Heawood: t = 2, 3 on a 12-cycle (v2 = 2) and the Hamiltonian 14-cycle
nE = heawood(); n, E, adj, eidx = build(nE)
cycles = all_cycles(adj, n)
CH12 = [c for c in cycles if len(c) == 12][0]
CH14 = [c for c in cycles if len(c) == 14][0]
for t in (2, 3):
    analyze('Heawood', nE, CH12, t, '12-cycle')
analyze('Heawood', nE, CH14, 3, '14-cycle')

# Mobius-Kantor: the four census-shallow t=2 cycles, at t = 2
nE = mobius_kantor(); n, E, adj, eidx = build(nE)
m = len(E)
cycles = all_cycles(adj, n)
shallow2 = []
for C in cycles:
    L = len(C)
    if v2(L) != 2: continue
    x = lift(C, eidx, m)
    ears = ears_of(adj, C)
    zs = ear_vectors(C, ears, x, eidx, m)
    ok = True
    for z in zs:
        delta = norm2(z) + 2 * dot(x, z)
        if v2(delta) >= 2: ok = False; break
    if ok: shallow2.append(C)
print('MK census-shallow t=2 cycles found: %d' % len(shallow2),
      flush=True)
for C in shallow2:
    analyze('MK', nE, C, 2, 'SHALLOW')
# and one MK cycle at t = 3 (module scale 4^9)
C16 = [c for c in cycles if len(c) == 16][0]
analyze('MK', nE, C16, 3, '16-cycle')
