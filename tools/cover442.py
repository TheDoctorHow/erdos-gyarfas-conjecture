"""cover442.py -- the 440 board through the 441 nexus lens, and the
decision of the ODD branch.

 (1) POLARIZATION = BOARD.  For every composite generated by the 440
     battery (all subsets of pairwise-compatible ears up to size 5,
     all arc choices, single-cycle validity by the topological XOR
     test):
       (i)  L - kept = |XOR of chosen arcs|
                     = sum over nonempty T of (-2)^{|T|-1}|cap_T A|
            -- 430's inclusion-exclusion law, verified on the board;
       (ii) when no C-edge is covered by 3 or more chosen arcs, the
            series truncates at pairs:
                kept = L - sum a_i + 2 sum_{i<j} |A_i cap A_j|
            -- exactly the lattice polarization |x + sum z_i|^2 of
            441.2 with cross terms <z_i, z_j> = |A_i cap A_j|.
     Consequence: every 440 board constraint
         sum_{used} T_i =/= -kept  (mod 16)
     is an instance of the 441 covering congruences; the board IS the
     covering problem, evaluated mod 2^{t+1} at t = 3.

 (2) THE DECISION.  Exhaustive forward-checking solver: bitmask
     domains, dynamic min-domain ordering, precomputed pair tables,
     incremental counters for k >= 3 constraints.  Protocol:
       (a) VALIDATION: reproduce 440's EVEN-branch UNSAT (arc 4,
           maxk 3) with the new engine;
       (b) EVEN branch, full battery maxk 5 (belt and braces);
       (c) ODD branch, extra arcs 4 and 8, full battery maxk 5 --
           the branch 440 left UNDECIDED.
     Output per run: SAT witness / UNSAT (exhaustive) / UNDECIDED,
     with node and time counts, honestly.
"""
import itertools, sys, time
sys.setrecursionlimit(10000)

L = 24

def build_board(extra_arc):
    ears = []
    for u in range(12):
        ears.append(('d', u, (u + 12) % L))
    for c in range(4):
        ears.append(('e', c, (c + extra_arc) % L))
    excl = {}
    for idx, (k, a, b) in enumerate(ears):
        if k == 'e':
            bad = {a % 12, b % 12}
            excl[idx] = {j for j in range(12) if j in bad}
    return ears, excl

def arc_mask(a, b, choice):
    """Bitmask of C-edges of the arc from a to b (choice 0) or b to a
    (choice 1), walking forward."""
    m = 0
    if choice == 0:
        j = a
        while j != b:
            m |= (1 << j); j = (j + 1) % L
    else:
        j = b
        while j != a:
            m |= (1 << j); j = (j + 1) % L
    return m

def pc(x): return bin(x).count('1')

def gen_composites(ears, excl, maxk=5):
    """Yield (sub, choices, kept, arcmasks) for single-cycle
    composites -- the 440 generator, with the arc data exposed."""
    n = len(ears)
    for k in range(1, maxk + 1):
        for sub in itertools.combinations(range(n), k):
            ok = True
            for idx in sub:
                if idx in excl and excl[idx] & set(sub): ok = False
            if not ok: continue
            feet = [(ears[i][1], ears[i][2]) for i in sub]
            for choices in itertools.product((0, 1), repeat=k):
                masks = [arc_mask(a, b, ch)
                         for (a, b), ch in zip(feet, choices)]
                xor = 0
                for m in masks: xor ^= m
                # composite adjacency: C edge j present iff bit j not
                # in xor; each ear a dummy 2-edge path
                adj = {}
                def add(x, y):
                    adj.setdefault(x, []).append(y)
                    adj.setdefault(y, []).append(x)
                for j in range(L):
                    if not (xor >> j) & 1:
                        add(('c', j), ('c', (j + 1) % L))
                for ii, (a, b) in enumerate(feet):
                    add(('c', a), ('m', ii)); add(('m', ii), ('c', b))
                if any(len(v) != 2 for v in adj.values()): continue
                verts = list(adj); seen = {verts[0]}; st = [verts[0]]
                while st:
                    x = st.pop()
                    for y in adj[x]:
                        if y not in seen: seen.add(y); st.append(y)
                if len(seen) != len(verts): continue
                kept = L - pc(xor)
                yield (sub, choices, kept, masks)

# =====================================================================
print('=== (1) POLARIZATION = BOARD ===', flush=True)
for extra_arc in (4, 8):
    ears, excl = build_board(extra_arc)
    tot = ie_ok = 0
    trunc_all = trunc_ok = 0
    cover3 = 0
    for (sub, choices, kept, masks) in gen_composites(ears, excl, 5):
        tot += 1
        k = len(masks)
        # (i) inclusion-exclusion law of 430
        s = 0
        for r in range(1, k + 1):
            for T in itertools.combinations(range(k), r):
                inter = (1 << L) - 1
                for i in T: inter &= masks[i]
                s += ((-2) ** (r - 1)) * pc(inter)
        if L - kept == s: ie_ok += 1
        # (ii) polarization truncation when coverage <= 2
        maxcov = max(sum((m >> j) & 1 for m in masks) for j in range(L))
        if maxcov >= 3:
            cover3 += 1
        else:
            trunc_all += 1
            t2 = (L - sum(pc(m) for m in masks)
                  + 2 * sum(pc(masks[i] & masks[j])
                            for i in range(k) for j in range(i + 1, k)))
            if kept == t2: trunc_ok += 1
    print('extra arc %2d: %5d composites | 430 incl-excl law %d/%d |'
          ' coverage<=2: %d (polarization exact %d/%d) |'
          ' coverage>=3: %d'
          % (extra_arc, tot, ie_ok, tot, trunc_all, trunc_ok,
             trunc_all, cover3), flush=True)

# =====================================================================
print(); print('=== (2) THE DECISION ===', flush=True)

def shallowness_domain(kind, a, b, parity):
    arcd = (b - a) % L; arcs = {arcd % 8, (L - arcd) % 8}
    mask = 0
    for v in range(parity, 16, 2):
        if v % 8 not in arcs:
            mask |= (1 << v)
    return mask

def constraints_for(ears, excl, maxk):
    seen = set()
    for (sub, choices, kept, masks) in gen_composites(ears, excl, maxk):
        seen.add((sub, kept))
    return sorted(seen)

def solve_fc(doms0, cons, budget):
    """Exhaustive DFS with forward checking.  doms0: bitmask domains.
    cons: list of (vars, kept) meaning sum T =/= -kept mod 16.
    Returns (status, witness, nodes)."""
    n = len(doms0)
    dom = list(doms0)
    val = [None] * n

    # singles prune domains up front
    big = []
    for vs, kept in cons:
        if len(vs) == 1:
            v = vs[0]
            forb = (-kept) % 16
            dom[v] &= ~(1 << forb)
            if dom[v] == 0: return 'UNSAT', None, 0
        else:
            big.append((vs, kept))
    # pair tables: pairtab[v][u][b] = forbidden bitmask for u given v=b
    pairtab = [dict() for _ in range(n)]
    k3 = []          # constraints with >= 3 vars
    for vs, kept in big:
        if len(vs) == 2:
            a, b = vs
            for (v, u) in ((a, b), (b, a)):
                tab = pairtab[v].setdefault(u, [0] * 16)
                for x in range(16):
                    tab[(x)] |= (1 << ((-kept - x) % 16))
        else:
            k3.append((vs, kept))
    by3 = [[] for _ in range(n)]
    for ci, (vs, kept) in enumerate(k3):
        for v in vs: by3[v].append(ci)
    cnt = [len(vs) for vs, _ in k3]
    ssum = [0] * len(k3)

    nodes = [0]
    def dfs():
        nodes[0] += 1
        if nodes[0] > budget: raise TimeoutError
        # min-domain variable
        v = -1; bs = 99
        for u in range(n):
            if val[u] is None:
                s = pc(dom[u])
                if s < bs: bs = s; v = u
        if v < 0: return True
        cand = dom[v]
        b = 0
        while cand:
            if cand & 1:
                val[v] = b
                trail = []
                ok = True
                # pair propagation
                for u, tab in pairtab[v].items():
                    m = tab[b]
                    if val[u] is not None:
                        if (m >> val[u]) & 1: ok = False; break
                    else:
                        rem = dom[u] & m
                        if rem:
                            dom[u] &= ~rem; trail.append((u, rem))
                            if dom[u] == 0: ok = False; break
                # k>=3 propagation (apply all, undo all)
                touched = []
                if ok:
                    for ci in by3[v]:
                        cnt[ci] -= 1; ssum[ci] += b; touched.append(ci)
                        if cnt[ci] == 0:
                            if (ssum[ci] + k3[ci][1]) % 16 == 0:
                                ok = False; break
                        elif cnt[ci] == 1:
                            vs = k3[ci][0]
                            u = next(w for w in vs if val[w] is None)
                            forb = (-k3[ci][1] - ssum[ci]) % 16
                            if (dom[u] >> forb) & 1:
                                dom[u] &= ~(1 << forb)
                                trail.append((u, 1 << forb))
                                if dom[u] == 0: ok = False; break
                if ok and dfs(): return True
                for ci in touched:
                    cnt[ci] += 1; ssum[ci] -= b
                for (u, rem) in trail: dom[u] |= rem
                val[v] = None
            cand >>= 1; b += 1
        return False
    try:
        sat = dfs()
        return ('SAT' if sat else 'UNSAT'), (list(val) if sat else None), \
            nodes[0]
    except TimeoutError:
        return 'UNDECIDED', None, nodes[0]

BUDGET = 5 * 10 ** 7
runs = [('VALIDATE EVEN', 4, 3, {'d': 0, 'e': 0}),
        ('EVEN full',     4, 5, {'d': 0, 'e': 0}),
        ('ODD  full',     4, 5, {'d': 1, 'e': 0}),
        ('EVEN full',     8, 5, {'d': 0, 'e': 0}),
        ('ODD  full',     8, 5, {'d': 1, 'e': 0})]
for label, extra_arc, maxk, pmap in runs:
    ears, excl = build_board(extra_arc)
    cons = constraints_for(ears, excl, maxk)
    doms = [shallowness_domain(k, a, b, pmap[k]) for (k, a, b) in ears]
    t0 = time.time()
    res, sol, nd = solve_fc(doms, cons, BUDGET)
    extra = ('  T = %s' % sol) if res == 'SAT' else ''
    print('%-13s arc %2d maxk %d: %4d constraints -> %-9s'
          ' [%d nodes, %.1fs]%s'
          % (label, extra_arc, maxk, len(cons), res, nd,
             time.time() - t0, extra), flush=True)
    if res == 'SAT':
        # independent full verification of the witness
        ok = all((sum(sol[v] for v in vs) + kept) % 16 != 0
                 for vs, kept in cons)
        okd = all((doms[i] >> sol[i]) & 1 for i in range(len(sol)))
        print('              witness verified against all constraints:'
              ' %s, domains: %s' % (ok, okd), flush=True)
