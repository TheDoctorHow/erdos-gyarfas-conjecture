"""Regenerate INDEX.md from the '## N. TITLE' headings of PROOF-PROGRAM.md.

    python tools/make_index.py            (run from the repository root)

A heading may continue on following '## ' lines that carry no number; those
are joined onto the title.  Line numbers are 1-based and refer to the file
as stored (CRLF line endings), so `sed -n 'START,ENDp'` extracts a section.
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'PROOF-PROGRAM.md')
DST = os.path.join(ROOT, 'INDEX.md')

NUMBERED = re.compile(r'^##\s+(\d+)\.\s*(.*\S)?\s*$')
CONTINUATION = re.compile(r'^##\s+(?!\d+\.)(.*\S)\s*$')


def main():
    with io.open(SRC, encoding='utf-8', newline='') as f:
        lines = f.read().split('\n')
    entries = []
    for i, raw in enumerate(lines, 1):
        line = raw.rstrip('\r')
        m = NUMBERED.match(line)
        if m:
            entries.append([int(m.group(1)), i, (m.group(2) or '').strip()])
            continue
        c = CONTINUATION.match(line)
        if c and not line.startswith('###') and entries:
            # only a continuation if it directly follows the previous heading
            if i - 1 <= entries[-1][1] + 1 + entries[-1][2].count('\n'):
                entries[-1][2] = (entries[-1][2] + ' ' + c.group(1)).strip()
    out = []
    out.append('# Index of PROOF-PROGRAM.md\n')
    out.append('Generated by `tools/make_index.py` - do not edit by hand.\n')
    out.append('`PROOF-PROGRAM.md` is about 3 MB and GitHub will not render it '
               'in the browser; use the raw view or a clone. To read one '
               'section, take its line number below and its successor\'s, then '
               '`sed -n \'START,ENDp\' PROOF-PROGRAM.md`, or '
               '`grep -n "^## 594\\." PROOF-PROGRAM.md`.\n')
    out.append('%d numbered sections, %d lines in total.\n'
               % (len(entries), len(lines)))
    out.append('| section | line | title |')
    out.append('|---:|---:|---|')
    for num, ln, title in entries:
        out.append('| %d | %d | %s |' % (num, ln, title.replace('|', '/')))
    io.open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', DST, ':', len(entries), 'sections')


if __name__ == '__main__':
    sys.exit(main())
